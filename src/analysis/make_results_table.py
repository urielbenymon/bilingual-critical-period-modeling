#!/usr/bin/env python

"""
Create compact paper-oriented summary tables for the class experiment.

Inputs:
    Contrast CSVs generated by analyze_trajectory_contrasts.py.

Outputs:
    1. A compact CSV containing the most important transformer-layer results.
    2. A text version that is easy to inspect and copy into notes.
    3. A compact terminal summary.

The main table focuses on:
    - German vs Finnish differences
    - L1 retention
    - L2 representational reorganization
    - EWC vs Sequential differences
    - Epoch 1 -> Final trajectory changes

The embedding layer is intentionally excluded from the main table because
its mean-pooled representations behaved very differently from the contextual
transformer layers and should be discussed separately.
"""

import argparse
from pathlib import Path

import pandas as pd


TRANSFORMER_LAYERS = [
    "transformer_layer_1",
    "transformer_layer_2",
]


def format_float(value, digits=4):
    """
    Format numeric values compactly for human-readable output.
    """
    if pd.isna(value):
        return ""

    return f"{value:.{digits}f}"


def load_csv(path):
    """
    Load and verify one required CSV.
    """
    path = Path(path)

    if not path.exists():
        raise FileNotFoundError(
            f"Required results file not found: {path}"
        )

    return pd.read_csv(path)


def filter_transformer_layers(df):
    """
    Keep only contextual transformer layers 1 and 2.
    """
    return df[
        df["layer_name"].isin(TRANSFORMER_LAYERS)
    ].copy()


def build_l1_language_rows(df):
    """
    Summarize Finnish - German differences in English L1 retention.

    Positive difference:
        Finnish condition remained MORE similar to English baseline.

    Negative difference:
        Finnish condition remained LESS similar to English baseline.
    """
    rows = []

    df = filter_transformer_layers(df)

    for _, row in df.iterrows():

        rows.append(
            {
                "analysis": "L1 retention",
                "comparison": "Finnish - German",
                "training_condition": row["training_condition"],
                "stage": row["stage"],
                "layer": row["layer_name"],
                "estimate": row["mean_difference"],
                "ci95_low": row["difference_ci95_low"],
                "ci95_high": row["difference_ci95_high"],
                "effect_size": row["paired_cohens_dz"],
                "effect_size_type": "paired Cohen's dz",
                "interpretation_direction": (
                    "positive = Finnish retains more L1 similarity"
                ),
            }
        )

    return rows


def build_l2_language_rows(df):
    """
    Summarize Finnish - German differences in L2 representation similarity.

    Negative difference:
        Finnish representations are farther from their pre-L2 baseline,
        meaning greater representational reorganization.
    """
    rows = []

    df = filter_transformer_layers(df)

    for _, row in df.iterrows():

        rows.append(
            {
                "analysis": "L2 reorganization",
                "comparison": "Finnish - German",
                "training_condition": row["training_condition"],
                "stage": row["stage"],
                "layer": row["layer_name"],
                "estimate": row["mean_difference"],
                "ci95_low": row["difference_ci95_low"],
                "ci95_high": row["difference_ci95_high"],
                "effect_size": row[
                    "hedges_g_finnish_vs_german"
                ],
                "effect_size_type": "Hedges' g",
                "interpretation_direction": (
                    "negative = Finnish reorganizes farther from baseline"
                ),
            }
        )

    return rows


def build_ewc_rows(df, analysis_name):
    """
    Summarize EWC - Sequential contrasts.

    Positive difference:
        EWC representations are more similar to the relevant baseline.

    Negative difference:
        EWC representations are less similar to the relevant baseline.
    """
    rows = []

    df = filter_transformer_layers(df)

    for _, row in df.iterrows():

        rows.append(
            {
                "analysis": analysis_name,
                "comparison": "EWC - Sequential",
                "training_condition": "EWC vs Sequential",
                "stage": row["stage"],
                "language": row["language_condition"],
                "layer": row["layer_name"],
                "estimate": row["mean_difference"],
                "ci95_low": row["difference_ci95_low"],
                "ci95_high": row["difference_ci95_high"],
                "effect_size": row["paired_cohens_dz"],
                "effect_size_type": "paired Cohen's dz",
                "interpretation_direction": (
                    "positive = EWC remains more similar to baseline"
                ),
            }
        )

    return rows


def build_stage_change_rows(df, analysis_name):
    """
    Summarize Final - Epoch 1 representational change.

    Positive:
        Final representation became more similar to baseline.

    Negative:
        Final representation became less similar to baseline.
    """
    rows = []

    df = filter_transformer_layers(df)

    for _, row in df.iterrows():

        rows.append(
            {
                "analysis": analysis_name,
                "comparison": "Final - Epoch 1",
                "training_condition": row["training_condition"],
                "language": row["language_condition"],
                "stage": "Epoch 1 -> Final",
                "layer": row["layer_name"],
                "estimate": row["mean_change"],
                "ci95_low": row["change_ci95_low"],
                "ci95_high": row["change_ci95_high"],
                "effect_size": row["paired_cohens_dz"],
                "effect_size_type": "paired Cohen's dz",
                "interpretation_direction": (
                    "positive = final state is more similar to baseline"
                ),
            }
        )

    return rows


def build_key_results_table(
    l1_language,
    l2_language,
    l1_ewc,
    l2_ewc,
    l1_stage,
    l2_stage,
):
    """
    Combine all transformer-level contrasts into one structured table.
    """

    rows = []

    rows.extend(
        build_l1_language_rows(l1_language)
    )

    rows.extend(
        build_l2_language_rows(l2_language)
    )

    rows.extend(
        build_ewc_rows(
            l1_ewc,
            "L1 retention",
        )
    )

    rows.extend(
        build_ewc_rows(
            l2_ewc,
            "L2 reorganization",
        )
    )

    rows.extend(
        build_stage_change_rows(
            l1_stage,
            "L1 retention",
        )
    )

    rows.extend(
        build_stage_change_rows(
            l2_stage,
            "L2 reorganization",
        )
    )

    df = pd.DataFrame(rows)

    # Ensure columns exist even where some row types do not use them.
    preferred_columns = [
        "analysis",
        "comparison",
        "language",
        "training_condition",
        "stage",
        "layer",
        "estimate",
        "ci95_low",
        "ci95_high",
        "effect_size",
        "effect_size_type",
        "interpretation_direction",
    ]

    for column in preferred_columns:
        if column not in df.columns:
            df[column] = ""

    return df[preferred_columns]


def print_key_findings(l1_language, l2_language, l1_ewc, l2_ewc):
    """
    Print a deliberately concise subset of the most important results.
    """

    print("\n" + "=" * 100)
    print("KEY TRANSFORMER-LAYER RESULTS")
    print("=" * 100)

    # ------------------------------------------------------------
    # L1 language contrast
    # ------------------------------------------------------------

    l1_seq_final = l1_language[
        (l1_language["training_condition"] == "Sequential")
        & (l1_language["stage"] == "Final")
        & (
            l1_language["layer_name"].isin(
                TRANSFORMER_LAYERS
            )
        )
    ]

    print("\n1. English L1 retention: Finnish - German, Sequential Final")

    for _, row in l1_seq_final.iterrows():

        print(
            f"   {row['layer_name']}: "
            f"difference={format_float(row['mean_difference'])}, "
            f"95% CI=[{format_float(row['difference_ci95_low'])}, "
            f"{format_float(row['difference_ci95_high'])}]"
        )

    # ------------------------------------------------------------
    # L2 language contrast
    # ------------------------------------------------------------

    l2_seq_final = l2_language[
        (l2_language["training_condition"] == "Sequential")
        & (l2_language["stage"] == "Final")
        & (
            l2_language["layer_name"].isin(
                TRANSFORMER_LAYERS
            )
        )
    ]

    print("\n2. L2 representation: Finnish - German, Sequential Final")

    for _, row in l2_seq_final.iterrows():

        print(
            f"   {row['layer_name']}: "
            f"difference={format_float(row['mean_difference'])}, "
            f"95% CI=[{format_float(row['difference_ci95_low'])}, "
            f"{format_float(row['difference_ci95_high'])}], "
            f"Hedges' g={format_float(row['hedges_g_finnish_vs_german'])}"
        )

    # ------------------------------------------------------------
    # Largest absolute EWC differences
    # ------------------------------------------------------------

    l1_ewc_transformer = filter_transformer_layers(l1_ewc)
    l2_ewc_transformer = filter_transformer_layers(l2_ewc)

    max_l1 = l1_ewc_transformer.loc[
        l1_ewc_transformer[
            "mean_difference"
        ].abs().idxmax()
    ]

    max_l2 = l2_ewc_transformer.loc[
        l2_ewc_transformer[
            "mean_difference"
        ].abs().idxmax()
    ]

    print("\n3. Largest absolute EWC - Sequential transformer-layer differences")

    print(
        "   L1 retention: "
        f"{max_l1['language_condition']} | "
        f"{max_l1['stage']} | "
        f"{max_l1['layer_name']} = "
        f"{format_float(max_l1['mean_difference'], 6)}"
    )

    print(
        "   L2 representation: "
        f"{max_l2['language_condition']} | "
        f"{max_l2['stage']} | "
        f"{max_l2['layer_name']} = "
        f"{format_float(max_l2['mean_difference'], 6)}"
    )

    print(
        "\nInterpretation reminder: the confidence intervals describe "
        "probe-sentence variation within one trained-model seed, not "
        "uncertainty across independent training runs."
    )


def save_text_table(df, path):
    """
    Save a readable fixed-width text copy of the compact table.
    """

    display_df = df.copy()

    for column in [
        "estimate",
        "ci95_low",
        "ci95_high",
        "effect_size",
    ]:
        display_df[column] = display_df[column].apply(
            lambda x: format_float(x)
        )

    path.write_text(
        display_df.to_string(index=False),
        encoding="utf-8",
    )


def main():

    parser = argparse.ArgumentParser()

    parser.add_argument(
        "--contrast_dir",
        default="analysis_outputs/class/contrasts",
        help="Directory containing contrast CSV files.",
    )

    parser.add_argument(
        "--output_dir",
        default="analysis_outputs/class/results_tables",
        help="Directory for compact results tables.",
    )

    args = parser.parse_args()

    contrast_dir = Path(args.contrast_dir)
    output_dir = Path(args.output_dir)

    output_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    print("Loading contrast results...")

    l1_stage = load_csv(
        contrast_dir / "l1_stage_changes.csv"
    )

    l2_stage = load_csv(
        contrast_dir / "l2_stage_changes.csv"
    )

    l1_ewc = load_csv(
        contrast_dir / "l1_ewc_contrasts.csv"
    )

    l2_ewc = load_csv(
        contrast_dir / "l2_ewc_contrasts.csv"
    )

    l1_language = load_csv(
        contrast_dir / "l1_language_contrasts.csv"
    )

    l2_language = load_csv(
        contrast_dir / "l2_language_contrasts.csv"
    )

    compact_df = build_key_results_table(
        l1_language=l1_language,
        l2_language=l2_language,
        l1_ewc=l1_ewc,
        l2_ewc=l2_ewc,
        l1_stage=l1_stage,
        l2_stage=l2_stage,
    )

    csv_path = (
        output_dir
        / "compact_transformer_results.csv"
    )

    text_path = (
        output_dir
        / "compact_transformer_results.txt"
    )

    compact_df.to_csv(
        csv_path,
        index=False,
    )

    save_text_table(
        compact_df,
        text_path,
    )

    print("Saved compact CSV:", csv_path)
    print("Saved readable table:", text_path)

    print_key_findings(
        l1_language=l1_language,
        l2_language=l2_language,
        l1_ewc=l1_ewc,
        l2_ewc=l2_ewc,
    )


if __name__ == "__main__":
    main()